class Collatz {
    public int solution(int num) {
        // [조건 1] 처음부터 1이 주어진 경우, 작업을 수행할 필요 없이 바로 0 반환
        if (num == 1) return 0;
        
        // [핵심] int 오버플로우 방지:
        // 연산 중간에 홀수 연산(n * 3 + 1)이 반복되면 21억(Integer.MAX_VALUE)을 넘을 수 있으므로
        // 64비트 정수형인 long으로 형변환하여 계산을 진행합니다.
        long n = num;
        int count = 0; // 작업 반복 횟수를 누적할 변수
        
        // [반복문] n이 1이 될 때까지 계속 작업 수행
        while (n != 1) {
            // [조건 2] 500번 반복할 때까지 1이 되지 않으면 -1 반환
            if (count == 500) return -1;
            
            // 1-1. 짝수라면 2로 나눔
            if (n % 2 == 0) {
                n /= 2;
            } 
            // 1-2. 홀수라면 3을 곱하고 1을 더함
            else {
                n = n * 3 + 1;
            }
            
            // 한 번 연산이 끝날 때마다 카운트 1 증가
            count++;
        }
        
        // 1이 되었을 때의 총 반복 횟수 반환
        return count;
    }
}
