// 원문의 class Solution 은 파일 이름에 맞춰 클래스 이름만 바꿨다. 줄 끝의 "//정렬해놔서 …" 는 원문에 있던 내 메모다.
import java.util.Arrays;

class HIndex {
    public int solution(int[] citations) {
        // 1. 논문 인용 횟수를 오름차순(낮은 것부터 높은 순)으로 정렬합니다.
        // 예: [3, 0, 6, 1, 5] -> [0, 1, 3, 5, 6]
        Arrays.sort(citations);
        
        // 전체 논문의 개수를 구합니다. (여기서는 5편)
        int n = citations.length;
        
        // 2. 인용 횟수가 적은 논문부터 차례대로 확인합니다.
        for (int i = 0; i < n; i++) {
            
            // 핵심 공식: 현재 논문을 포함하여 "내 뒤에 남아 있는 논문의 개수"를 구합니다.
            // i가 0일 때: 남은 논문 5편 ([0, 1, 3, 5, 6]) -> h = 5
            // i가 1일 때: 남은 논문 4편 ([1, 3, 5, 6])     -> h = 4
            // i가 2일 때: 남은 논문 3편 ([3, 5, 6])        -> h = 3  <-- 바로 이 순간!
            int h = n - i; 
            
            // 3. "현재 논문의 인용 횟수"가 "남은 논문 개수(h)" 이상인지 확인합니다.
            // - i=0 일 때: citations[0]인 0 >= 5 ? 거짓 (탈락)
            // - i=1 일 때: citations[1]인 1 >= 4 ? 거짓 (탈락)
            // - i=2 일 때: citations[2]인 3 >= 3 ? 참! (이 순간의 h인 3이 바로 H-Index)
            if (citations[i] >= h) {
                return h; // 조건을 만족하는 최초의 순간(최댓값)을 반환하고 종료
            } //정렬해놔서 갯수를 안 세도 되는거임
        }
        
        // 만약 모든 논문이 0번 인용되었거나 한 편도 조건에 안 맞으면 H-Index는 0
        return 0;
    }
}
